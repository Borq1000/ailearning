import { describe, expect, it } from 'vitest'
import { plural } from './plural'

const forms = ['карточка', 'карточки', 'карточек'] as const

describe('plural', () => {
  it.each([
    [0, 'карточек'],
    [1, 'карточка'],
    [2, 'карточки'],
    [4, 'карточки'],
    [5, 'карточек'],
    [11, 'карточек'],
    [12, 'карточек'],
    [14, 'карточек'],
    [21, 'карточка'],
    [22, 'карточки'],
    [25, 'карточек'],
    [101, 'карточка'],
    [111, 'карточек'],
  ])('%i → %s', (n, word) => {
    expect(plural(n, forms)).toBe(word)
  })
})
